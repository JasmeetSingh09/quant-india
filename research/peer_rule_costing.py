"""
peer_rule_costing.py — cost candidate peer rule R on a frozen scan cycle.

Owner decision 2026-10-14 (docs/PEER_METHODOLOGY_DECISION_2026-10-14.md). This
GENERATES one read-only SQL statement; it runs nothing and writes nothing. The
statement reads the fingerprinted cycle 2026-10-14 tables plus an inline copy
of the classification file, and returns one row per sensitivity setting.

    python research/peer_rule_costing.py CLASSIFICATION.csv > rule_r.sql
    python research/peer_rule_costing.py CLASSIFICATION.csv --settings 3:2:kept,3:2:renorm

The full grid is K in {2,3,4,5} x MIN_VALID in {2,3} x LEG_RULE in {kept,
renorm} (16 rows). Supabase's statement timeout may need it split with
--settings. Smoke-tested 2026-10-14 on a 50-stock toy classification (Yahoo
industry standing in for basic industry): it ran, and its categories summed to
the 2,462 scored stocks. The toy numbers mean nothing.

CLASSIFICATION.csv columns (header row required): symbol, basic_industry,
industry. symbol is the NSE symbol without ".NS". Extra columns are ignored.

Rule R as approved for costing (owner, 2026-10-14):
  - peer group = same basic industry; if fewer than K eligible peers for a
    measure, widen to the same industry for that measure; no wider fallback.
  - eligibility is per measure: a peer counts for P/E only if its P/E > 0,
    for P/B only if its P/B > 0 (negative multiples excluded, audit D-06).
  - peers ordered by stored market cap descending, ties by ticker; the first
    VALUE_PEERS_USED (3) eligible are used.
  - a measure is measured only if the stock's own multiple is > 0 and at
    least MIN_VALID eligible peers were used; otherwise "not measured".
  - neither measure measured -> value not measured (contributes 0; weights
    not rescaled, per the methodology); no market-average substitute.
  - stocks not in the file -> value not measured (no fallback).
  - distress (both own multiples <= 0) keeps today's -0.5 / 0.6: it uses no
    peers.
  - one measure measured: LEG_RULE 'kept' (missing measure contributes 0,
    weight kept: numerically today's "sits at the mean") or 'renorm'
    (weights renormalised over the measured measure). Owner decision pending.
Unchanged from today: spread floors 1 (P/E) and 0.5 (P/B), weights -0.6/-0.4,
tanh(raw/2), confidence min(1, 0.5 + 0.1 x P/E peers) halved on one measure.
Assumption A1: widening is decided per measure. Assumption A2: peer multiples
are each peer's own stored value for the cycle (one value per peer per cycle).
"""
import csv
import sys

CYCLE = "2026-10-14"
SETTINGS = [(k, m, leg) for k in (2, 3, 4, 5) for m in (2, 3) for leg in ("kept", "renorm")]
PEERS_USED = 3


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def build(rows, settings_list=None):
    cls = ",\n  ".join(f"({q(r['symbol'].strip().upper())}, {q(r['basic_industry'].strip())}, "
                       f"{q(r['industry'].strip())})" for r in rows
                       if r.get("symbol") and r.get("basic_industry"))
    settings = ", ".join(f"({k}, {m}, {q(leg)})" for k, m, leg in (settings_list or SETTINGS))
    return f"""-- generated by research/peer_rule_costing.py; read-only; cycle {CYCLE}
WITH cls(symbol, basic, industry) AS (VALUES
  {cls}),
settings(k, minv, leg) AS (VALUES {settings}),
own AS MATERIALIZED (SELECT ticker,
    max(value_num) FILTER (WHERE input_name='pe_ratio') pe,
    max(value_num) FILTER (WHERE input_name='pb_ratio') pb,
    max(value_num) FILTER (WHERE input_name='legs_used') legs
  FROM factor_inputs WHERE cycle_id={q(CYCLE)} AND factor='value'
    AND input_name IN ('pe_ratio','pb_ratio','legs_used') GROUP BY ticker),
pc AS MATERIALIZED (SELECT ticker, count(*) FILTER (WHERE peer_pe IS NOT NULL AND peer_pe<>0) npe_today
  FROM factor_input_peers WHERE cycle_id={q(CYCLE)} GROUP BY ticker),
u AS MATERIALIZED (SELECT a.ticker, a.alpha_score a0, a.signal s0, a.confidence c0, a.market_cap mc, a.value v0,
    o.pe, o.pb, o.legs, c.basic, c.industry,
    CASE WHEN o.legs IS NULL THEN 0 WHEN o.legs=0 THEN 0.6
         ELSE least(1.0, 0.5+0.1*coalesce(pc.npe_today,0)) * CASE WHEN o.legs<2 THEN 0.5 ELSE 1 END END vc0
  FROM alpha_scan2 a LEFT JOIN own o ON o.ticker=a.ticker LEFT JOIN pc ON pc.ticker=a.ticker
  LEFT JOIN cls c ON c.symbol || '.NS' = a.ticker
  WHERE a.cycle={q(CYCLE)} AND a.error IS NULL),
m(metric) AS (VALUES ('pe'), ('pb')),
-- every eligible peer of every classified stock, per measure and level, in rule order
el AS MATERIALIZED (
  SELECT x.ticker, m.metric, lv.level, y.ticker peer,
         CASE m.metric WHEN 'pe' THEN y.pe ELSE y.pb END val,
         row_number() OVER (PARTITION BY x.ticker, m.metric, lv.level ORDER BY y.mc DESC NULLS LAST, y.ticker) rn,
         count(*) OVER (PARTITION BY x.ticker, m.metric, lv.level) n
  FROM u x CROSS JOIN m CROSS JOIN (VALUES ('basic'), ('industry')) lv(level)
  JOIN u y ON y.ticker <> x.ticker
          AND ((lv.level='basic' AND y.basic = x.basic) OR (lv.level='industry' AND y.industry = x.industry))
          AND (CASE m.metric WHEN 'pe' THEN y.pe ELSE y.pb END) > 0
  WHERE x.basic IS NOT NULL),
cnt AS (SELECT ticker, metric, level, max(n) n FROM el GROUP BY 1,2,3),
pick AS (  -- chosen level per setting, stock and measure (assumption A1: per measure)
  SELECT s.k, s.minv, s.leg, x.ticker, m.metric,
         CASE WHEN coalesce(b.n,0) >= s.k THEN 'basic'
              WHEN x.industry IS NOT NULL AND coalesce(i.n,0) > coalesce(b.n,0) THEN 'industry'
              ELSE 'basic' END level
  FROM settings s CROSS JOIN u x CROSS JOIN m
  LEFT JOIN cnt b ON b.ticker=x.ticker AND b.metric=m.metric AND b.level='basic'
  LEFT JOIN cnt i ON i.ticker=x.ticker AND i.metric=m.metric AND i.level='industry'
  WHERE x.basic IS NOT NULL),
st AS (SELECT p.k, p.minv, p.leg, p.ticker, p.metric, p.level, count(e.val) n_used, avg(e.val) mu, stddev_pop(e.val) sd
  FROM pick p LEFT JOIN el e ON e.ticker=p.ticker AND e.metric=p.metric AND e.level=p.level AND e.rn <= {PEERS_USED}
  GROUP BY 1,2,3,4,5,6),
z AS (SELECT s.k, s.minv, s.leg, x.ticker,
    max(CASE WHEN st.metric='pe' AND x.pe > 0 AND st.n_used >= s.minv THEN (x.pe - st.mu)/greatest(st.sd, 1) END) zpe,
    max(CASE WHEN st.metric='pb' AND x.pb > 0 AND st.n_used >= s.minv THEN (x.pb - st.mu)/greatest(st.sd, 0.5) END) zpb,
    max(CASE WHEN st.metric='pe' THEN st.n_used END) npe_used,
    max(CASE WHEN st.metric='pe' AND st.level='industry' THEN 1 ELSE 0 END)
      + max(CASE WHEN st.metric='pb' AND st.level='industry' THEN 1 ELSE 0 END) widened
  FROM settings s CROSS JOIN u x LEFT JOIN st ON st.ticker=x.ticker AND st.k=s.k AND st.minv=s.minv AND st.leg=s.leg
  GROUP BY 1,2,3,4),
r AS (SELECT z.*, x.a0, x.s0, x.c0, x.mc, x.v0, x.vc0, x.legs, x.basic,
    CASE WHEN x.legs = 0 THEN 'distress (kept)'
         WHEN x.legs IS NULL THEN 'no valuation data (unchanged)'
         WHEN x.basic IS NULL THEN 'not in classification file -> not measured'
         WHEN z.zpe IS NOT NULL AND z.zpb IS NOT NULL THEN 'classified, both measures'
         WHEN z.zpe IS NOT NULL OR z.zpb IS NOT NULL THEN 'classified, one measure'
         ELSE 'classified, too few valid peers -> not measured' END cat
  FROM z JOIN u x ON x.ticker=z.ticker),
v AS (SELECT r.*,
    CASE WHEN cat LIKE 'distress%' OR cat LIKE 'no valuation%' THEN v0
         WHEN zpe IS NULL AND zpb IS NULL THEN 0
         WHEN leg='kept' THEN tanh((-0.6*coalesce(zpe,0) - 0.4*coalesce(zpb,0))/2)
         ELSE tanh(((-0.6*coalesce(zpe,0) - 0.4*coalesce(zpb,0))
                    / ((CASE WHEN zpe IS NULL THEN 0 ELSE 0.6 END) + (CASE WHEN zpb IS NULL THEN 0 ELSE 0.4 END)))/2) END v1,
    CASE WHEN cat LIKE 'distress%' OR cat LIKE 'no valuation%' THEN vc0
         WHEN zpe IS NULL AND zpb IS NULL THEN 0
         ELSE least(1.0, 0.5+0.1*coalesce(npe_used,0)) * CASE WHEN zpe IS NULL OR zpb IS NULL THEN 0.5 ELSE 1 END END vc1
  FROM r),
f AS (SELECT v.*, round((a0 + 15*(v1 - v0))::numeric, 2) a1, c0 - 0.15*vc0 + 0.15*vc1 c1 FROM v),
g AS (SELECT f.*, CASE WHEN a1>40 THEN 'STRONG BUY' WHEN a1>15 THEN 'BUY' WHEN a1< -40 THEN 'STRONG SELL'
                       WHEN a1< -15 THEN 'SELL' ELSE 'NEUTRAL' END s1 FROM f),
t0 AS (SELECT k, minv, leg, ticker, a0 a, row_number() OVER (PARTITION BY k, minv, leg ORDER BY mc DESC) cr FROM g WHERE c0>=0.3 AND mc IS NOT NULL),
t1 AS (SELECT k, minv, leg, ticker, a1 a, row_number() OVER (PARTITION BY k, minv, leg ORDER BY mc DESC) cr FROM g WHERE c1>=0.3 AND mc IS NOT NULL),
tt0 AS (SELECT *, CASE WHEN cr<=100 THEN 'L' WHEN cr<=250 THEN 'M' ELSE 'S' END tier FROM t0),
tt1 AS (SELECT *, CASE WHEN cr<=100 THEN 'L' WHEN cr<=250 THEN 'M' ELSE 'S' END tier FROM t1),
k0 AS (SELECT *, row_number() OVER (PARTITION BY k, minv, leg, tier ORDER BY a DESC, ticker) tr FROM tt0),
k1 AS (SELECT *, row_number() OVER (PARTITION BY k, minv, leg, tier ORDER BY a DESC, ticker) tr FROM tt1)
SELECT g.k, g.minv, g.leg,
  count(*) total,
  count(*) FILTER (WHERE cat='classified, both measures') cls_both,
  count(*) FILTER (WHERE cat='classified, one measure') cls_one,
  count(*) FILTER (WHERE cat LIKE 'classified, too few%') cls_too_few,
  count(*) FILTER (WHERE cat LIKE 'not in classification%') unclassified,
  count(*) FILTER (WHERE cat LIKE 'distress%') distress,
  count(*) FILTER (WHERE cat LIKE 'no valuation%') no_data,
  count(*) FILTER (WHERE widened > 0) widened_to_industry,
  count(*) FILTER (WHERE abs(a1 - a0) >= 0.01) scores_changed,
  round(avg(abs(a1 - a0)) FILTER (WHERE abs(a1 - a0) >= 0.01)::numeric, 2) mean_abs_change,
  count(*) FILTER (WHERE s1 <> s0) label_flips,
  count(*) FILTER (WHERE s1 <> s0 AND s0 IN ('BUY','STRONG BUY')) flips_out_of_buy,
  count(*) FILTER (WHERE s1 <> s0 AND s1 IN ('BUY','STRONG BUY')) flips_into_buy,
  count(*) FILTER (WHERE c0 >= 0.3 AND c1 < 0.3) leave_tiers,
  (SELECT count(*) FROM k0 WHERE k0.k=g.k AND k0.minv=g.minv AND k0.leg=g.leg AND tr <= 10
     AND NOT EXISTS (SELECT 1 FROM k1 WHERE k1.k=k0.k AND k1.minv=k0.minv AND k1.leg=k0.leg AND k1.tier=k0.tier
                     AND k1.ticker=k0.ticker AND k1.tr <= 10)) top10_slots_changed,
  (SELECT count(*) FROM k0 JOIN k1 USING (k, minv, leg, ticker) WHERE k0.k=g.k AND k0.minv=g.minv AND k0.leg=g.leg
     AND (k0.tier <> k1.tier OR k0.tr <> k1.tr)) tier_rank_changed
FROM g GROUP BY g.k, g.minv, g.leg ORDER BY g.k, g.minv, g.leg;
"""


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    with open(sys.argv[1], newline="", encoding="utf-8-sig") as fh:
        rows = list(csv.DictReader(fh))
    missing = {"symbol", "basic_industry", "industry"} - set(rows[0] if rows else {})
    if missing:
        sys.exit(f"classification file lacks columns: {sorted(missing)}")
    chosen = None
    if "--settings" in sys.argv:
        chosen = []
        for item in sys.argv[sys.argv.index("--settings") + 1].split(","):
            k, m, leg = item.split(":")
            if leg not in ("kept", "renorm"):
                sys.exit(f"leg rule must be kept or renorm, not {leg}")
            chosen.append((int(k), int(m), leg))
    print(build(rows, chosen))
